/// Global service locator instance

final GetIt getIt = GetIt.instance;

/// Configures all dependency injection bindings.
/// Generated by build_runner from @injectable and @module annotations.
@InjectableInit()
Future<void> configureDependencies({
  AppDependencyModule? appModule,
}) async {
  // App-specific bindings must exist before the generated shared graph is
  // built because shared services depend on them by interface. The nullable
  // compatibility path lets older app targets migrate independently; new
  // app entry points should always provide a module.
  appModule?.register(getIt);
  await getIt.init();
}

/// Bootstraps the entire application.
///
/// Call this once from main() before runApp().
Future<void> bootstrap({AppDependencyModule? appModule}) async {
  installPocketCoderGlobalErrorHandlers();
  debugPrint('Bootstrap: Starting...');

  // Fix for Chrome Incognito offline detection bug in connectivity_plus
  if (kIsWeb) {
    debugPrint('Bootstrap: Setting connectivity override for Web');
    ConnectivityPlatform.instance = WebConnectivityOverride();
  }

  try {
    debugPrint('Bootstrap: Configuring dependencies...');
    await configureDependencies(appModule: appModule);
    if (!getIt.isRegistered<AuthSessionCoordinator>()) {
      getIt.registerLazySingleton<AuthSessionCoordinator>(
        () => AuthSessionCoordinator(getIt<IAuthRepository>()),
      );
    }
    getIt<PocketCoderApiClient>().setAuthSessionCoordinator(
      getIt<AuthSessionCoordinator>(),
    );
    BaseDao.configureSessionCoordinator(getIt<AuthSessionCoordinator>());
    if (!getIt.isRegistered<DeploymentCacheEffects>()) {
      getIt.registerLazySingleton<DeploymentCacheEffects>(
        () => DeploymentCacheEffects(
          getIt<AuthSessionCoordinator>(),
          getIt<PocketBase>(),
        ),
      );
    }
    getIt<DeploymentCacheEffects>().start();
    final httpClient = getIt<http.Client>();
    if (httpClient is AuthAwareHttpClient) {
      httpClient.state.refresh = getIt<AuthSessionCoordinator>().refresh;
    }
    debugPrint('Bootstrap: Dependencies configured');

    // Initialize the push service
    final pushService = getIt<PushService>();
    await pushService.initialize();

    // Initialize the billing service
    final billingService = getIt<BillingService>();
    await billingService.initialize();

    // Start after push and billing initialization. The coordinator replay
    // handles an already-persisted session without blocking bootstrap.
    if (!getIt.isRegistered<AuthSessionEffects>()) {
      getIt.registerLazySingleton<AuthSessionEffects>(
        () => AuthSessionEffects(
          getIt<AuthSessionCoordinator>(),
          billingService,
          pushService,
        ),
      );
    }
    getIt<AuthSessionEffects>().start();

    // 2. Register UI flow service (depends on localization/feedback/loading)
    debugPrint('Bootstrap: Registering UI flow service...');
    _registerUiFlowService();
    debugPrint('Bootstrap: UI flow service registered');

    // 3. Configure ErrorPrivserver for privacy-preserving error reporting
    debugPrint('Bootstrap: Configuring ErrorPrivserver...');
    _configureErrorPrivserver();
    await pocketCoderDiagnosticCapture.flush();
    debugPrint('Bootstrap: ErrorPrivserver configured');

    debugPrint('Bootstrap: Complete');
  } catch (e, stack) {
    debugPrint('Bootstrap: FAILED - $e');
    debugPrint('Bootstrap: Stack trace:\n$stack');
    await pocketCoderDiagnosticCapture.capture(
      error: e,
      stackTrace: stack,
      source: 'Bootstrap',
      operation: 'startup',
    );
    rethrow;
  }
}

void _registerUiFlowService() {
  if (!getIt.isRegistered<cubit_ui_flow.IUiFlowService>()) {
    getIt.registerLazySingleton<cubit_ui_flow.IUiFlowService>(
      () => cubit_ui_flow.UiFlowService(
        localization: getIt<cubit_ui_flow.ILocalizationService>(),
        feedback: getIt<cubit_ui_flow.IFeedbackService>(),
        loading: getIt<cubit_ui_flow.ILoadingService>(),
      ),
    );
  }
}

/// Configure ErrorPrivserver for privacy-preserving error reporting.
void _configureErrorPrivserver() {
  ErrorPrivserver.configure(
    ErrorPrivserverConfig(
      storage: getIt<ErrorBoxStorage>(),
      reporter: (_) async =>
          false, // no-op: no network transmission, see spec §3
      errorCodeMapper: PocketCoderErrorCodeMapper.mapError,
      exceptionMapper: (error) => getIt<IExceptionKeyMapper>().map(error),
    ),
  );
}
